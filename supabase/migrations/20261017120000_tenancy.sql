-- 6. Functions and triggers -----------------------------------------------------

CREATE OR REPLACE FUNCTION "public"."handle_new_user"() RETURNS "trigger"
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
declare
  app_metadata jsonb;
  new_organisation_id uuid;
  new_role public.membership_role;
begin
  -- Runs as a deferred constraint trigger, at commit: Auth inserts the user
  -- first and writes app_metadata in a second statement, so the row is
  -- re-read here instead of trusting NEW.
  select u.raw_app_meta_data into app_metadata
  from auth.users u
  where u.id = new.id;

  -- The organisation comes from app metadata, which only the service role can
  -- set. User metadata is editable by the user and is never trusted for this.
  -- No organisation means the whole sign-up is rolled back: there is no
  -- self-signup into Re-entry.
  new_organisation_id := nullif(app_metadata ->> 'organisation_id', '')::uuid;
  if new_organisation_id is null then
    raise exception 'New users must be created with an organisation in app_metadata.organisation_id'
      using errcode = 'P0001';
  end if;

  new_role := coalesce(nullif(app_metadata ->> 'role', ''), 'key_worker')::public.membership_role;

  insert into public.memberships (organisation_id, user_id, role)
  values (new_organisation_id, new.id, new_role);

  insert into public.sales (first_name, last_name, email, user_id, administrator, organisation_id)
  values (
    coalesce(new.raw_user_meta_data ->> 'first_name', new.raw_user_meta_data -> 'custom_claims' ->> 'first_name', 'Pending'),
    coalesce(new.raw_user_meta_data ->> 'last_name', new.raw_user_meta_data -> 'custom_claims' ->> 'last_name', 'Pending'),
    new.email,
    new.id,
    new_role = 'org_admin',
    new_organisation_id
  );
  return new;
end;
$$;

CREATE OR REPLACE FUNCTION "public"."handle_organisation_created"() RETURNS "trigger"
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
begin
  insert into public.configuration (organisation_id) values (new.id);
  return new;
end;
$$;

CREATE OR REPLACE FUNCTION "public"."handle_sale_administrator_changed"() RETURNS "trigger"
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
begin
  -- Keeps memberships.role in step with the legacy sales.administrator flag
  -- that the existing admin screens and the users edge function still set.
  -- Session 2 removes sales.administrator and this trigger.
  update public.memberships
  set role = case
    when new.administrator then 'org_admin'::public.membership_role
    when role = 'org_admin' then 'key_worker'::public.membership_role
    else role
  end
  where user_id = new.user_id;
  return new;
end;
$$;

CREATE OR REPLACE FUNCTION "public"."is_admin"() RETURNS boolean
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
begin
  return exists (
    select 1 from public.memberships
    where user_id = auth.uid() and role = 'org_admin'
  );
end;
$$;

-- Deferred to commit so it sees the app_metadata Auth writes after the insert.
drop trigger on_auth_user_created on auth.users;
create constraint trigger on_auth_user_created
    after insert on auth.users
    deferrable initially deferred
    for each row execute function public.handle_new_user();

create or replace trigger on_organisation_created
    after insert on public.organisations
    for each row execute function public.handle_organisation_created();

create or replace trigger on_sale_administrator_changed
    after update of administrator on public.sales
    for each row
    when (old.administrator is distinct from new.administrator)
    execute function public.handle_sale_administrator_changed();

-- 7. Row-level security ------------------------------------------------------------

-- Drop every existing policy on the tables this migration re-secures: they
-- were all `using (true)`, i.e. visible to every signed-in user.
do $$
declare
  p record;
begin
  for p in
    select policyname, tablename
    from pg_policies
    where schemaname = 'public'
      and tablename in ('companies', 'contacts', 'contact_notes', 'deals', 'deal_notes',
                        'sales', 'tags', 'tasks', 'configuration', 'favicons_excluded_domains')
  loop
    execute format('drop policy %I on public.%I', p.policyname, p.tablename);
  end loop;
end;
$$;

