-- 3. Backfill existing data into a default organisation -----------------------

do $$
declare
  default_organisation_id uuid;
begin
  if exists (select 1 from public.sales)
    or exists (select 1 from public.companies)
    or exists (select 1 from public.contacts)
    or exists (select 1 from public.deals)
    or exists (select 1 from public.tags)
  then
    insert into public.organisations (name)
    values ('Default organisation')
    returning id into default_organisation_id;

    update public.companies set organisation_id = default_organisation_id;
    update public.contacts set organisation_id = default_organisation_id;
    update public.contact_notes set organisation_id = default_organisation_id;
    update public.deals set organisation_id = default_organisation_id;
    update public.deal_notes set organisation_id = default_organisation_id;
    update public.sales set organisation_id = default_organisation_id;
    update public.tags set organisation_id = default_organisation_id;
    update public.tasks set organisation_id = default_organisation_id;
    update public.configuration set organisation_id = default_organisation_id;

    insert into public.memberships (organisation_id, user_id, role)
    select
      default_organisation_id,
      s.user_id,
      case when s.administrator then 'org_admin'::public.membership_role
           else 'key_worker'::public.membership_role end
    from public.sales s;
  end if;

  -- The old single global configuration row has no organisation to belong to
  -- on an empty database; on_organisation_created recreates one per organisation.
  delete from public.configuration where organisation_id is null;

  -- tasks.sales_id had no foreign key before; clear any dangling values so the
  -- new composite key can be added.
  update public.tasks t
  set sales_id = null
  where t.sales_id is not null
    and not exists (select 1 from public.sales s where s.id = t.sales_id);
end;
$$;

