--
-- 5. Audit: views of contacts are no longer logged; key workers read the
-- history of their people's case notes and actions
--

create or replace function public.log_record_view(table_name text, record_id bigint)
returns void
language plpgsql
security definer
set search_path to ''
as $$
declare
  record_organisation_id uuid;
begin
  case log_record_view.table_name
    when 'service_users' then
      select su.organisation_id into record_organisation_id
      from public.service_users su
      where su.id = log_record_view.record_id
        and private.can_access_assigned(su.organisation_id, su.assigned_worker_id);
    when 'support_profiles' then
      select su.organisation_id into record_organisation_id
      from public.support_profiles sp
        join public.service_users su on su.id = sp.service_user_id
      where sp.id = log_record_view.record_id
        and private.can_access_assigned(su.organisation_id, su.assigned_worker_id);
    else
      raise exception 'Views of % are not logged', log_record_view.table_name using errcode = '22023';
  end case;

  if record_organisation_id is null then
    raise exception 'Record not found' using errcode = '42501';
  end if;

  insert into public.audit_log (organisation_id, actor_user_id, action, table_name, record_id)
  values (record_organisation_id, auth.uid(), 'view', log_record_view.table_name, log_record_view.record_id::text);
end;
$$;

create policy "Leads read the log, key workers their people's history" on public.audit_log for select to authenticated
    using (
        organisation_id = (select private.current_organisation_id())
        and (
            (select private.sees_all_records())
            or (table_name = 'service_users' and exists (select 1 from public.service_users su where su.id::text = record_id))
            or (table_name = 'support_profiles' and exists (select 1 from public.support_profiles sp where sp.id::text = record_id))
            or (table_name = 'escalations' and exists (select 1 from public.escalations e where e.id::text = record_id))
            or (table_name = 'case_notes' and exists (select 1 from public.case_notes n where n.id::text = record_id))
            or (table_name = 'case_actions' and exists (select 1 from public.case_actions a where a.id::text = record_id))
        )
    );

--
-- 6. The profile's Audit Trail includes case notes and actions
--

create or replace function public.service_user_history(service_user_id bigint, max_results integer default 50)
returns table (
    id bigint,
    created_at timestamp with time zone,
    action public.audit_action,
    table_name text,
    record_id text,
    actor_name text,
    before jsonb,
    after jsonb
)
language sql
stable
set search_path to ''
as $$
  select
    l.id,
    l.created_at,
    l.action,
    l.table_name,
    l.record_id,
    coalesce(s.first_name || ' ' || s.last_name, 'System') as actor_name,
    l.before,
    l.after
  from public.audit_log l
    left join public.sales s on s.user_id = l.actor_user_id
  where (l.table_name = 'service_users' and l.record_id = service_user_history.service_user_id::text)
    or (l.table_name in ('support_profiles', 'escalations', 'case_notes', 'case_actions')
        and coalesce(l.after, l.before) ->> 'service_user_id' = service_user_history.service_user_id::text)
    or (l.table_name = 'support_profiles' and l.action = 'view' and l.record_id = (
        select sp.id::text from public.support_profiles sp where sp.service_user_id = service_user_history.service_user_id
    ))
  order by l.created_at desc, l.id desc
  limit least(greatest(coalesce(max_results, 50), 1), 200)
$$;
