--
-- Retire the Atomic CRM tables and add case notes and actions.
--
-- Nothing in the app has used contacts, companies, deals, tasks, tags or
-- their notes since Session 4. Dropping them also removes the triggers that
-- sent contact emails to gravatar.com and email domains to favicon.show
-- (finding F7), the global search over those tables, merge_contacts, and the
-- note attachment machinery (the `notes/` storage folder and the deletion
-- queue). Phase 1 holds synthetic data only, so no rows need carrying over.
--
-- Case notes and actions replace contact notes and tasks, attached to
-- service users instead (see 08_service_users_case_notes.sql).
--

--
-- 1. Drop the CRM views, search and functions
--

drop view if exists public.activity_log;
drop view if exists public.companies_summary;
drop view if exists public.contacts_summary;

drop function if exists public.global_search(text, text[], integer);
drop function if exists public.merge_contacts(bigint, bigint);

--
-- 2. Storage: only organisation-shared files (avatars, branding) remain
--

drop policy if exists "Attachments: members upload into their organisation" on storage.objects;
drop policy if exists "Attachments: members read what they may see" on storage.objects;

create policy "Attachments: members upload into their organisation" on storage.objects for insert to authenticated
    with check (
        bucket_id = 'attachments'
        and (storage.foldername(name))[1] = (select private.current_organisation_id())::text
        and (storage.foldername(name))[2] = 'shared'
    );

create policy "Attachments: members read what they may see" on storage.objects for select to authenticated
    using (
        bucket_id = 'attachments'
        and (storage.foldername(name))[1] = (select private.current_organisation_id())::text
        and (storage.foldername(name))[2] = 'shared'
    );

-- The audit log policy is recreated in section 5, once the case tables exist.
drop policy if exists "Leads read the log, key workers their people's history" on public.audit_log;

