-- Extensions
create extension if not exists "http" with schema "extensions";
create extension if not exists "citext" with schema "extensions";

create table public.companies (
    id bigint generated by default as identity primary key,
    created_at timestamp with time zone not null default now(),
    name text not null,
    sector text,
    size smallint,
    linkedin_url text,
    website extensions.citext,
    phone_number text,
    address text,
    zipcode text,
    city text,
    state_abbr text,
    sales_id bigint,
    context_links json,
    country text,
    description text,
    revenue text,
    tax_identifier text,
    logo jsonb,
    organisation_id uuid not null default private.current_organisation_id()
);

create table public.contacts (
    id bigint generated by default as identity primary key,
    first_name text,
    last_name text,
    gender text,
    title text,
    background text,
    avatar jsonb,
    first_seen timestamp with time zone,
    last_seen timestamp with time zone,
    has_newsletter boolean,
    status text,
    tags bigint[],
    company_id bigint,
    sales_id bigint,
    linkedin_url text,
    email_jsonb jsonb,
    phone_jsonb jsonb,
    organisation_id uuid not null default private.current_organisation_id()
);

create table public.contact_notes (
    id bigint generated by default as identity (sequence name public."contactNotes_id_seq") not null,
    contact_id bigint not null,
    text text,
    date timestamp with time zone default now(),
    sales_id bigint,
    status text,
    attachments jsonb[],
    organisation_id uuid not null default private.current_organisation_id()
);

create table public.deals (
    id bigint generated by default as identity primary key,
    name text not null,
    company_id bigint,
    contact_ids bigint[],
    category text,
    stage text not null,
    description text,
    amount bigint,
    created_at timestamp with time zone not null default now(),
    updated_at timestamp with time zone not null default now(),
    archived_at timestamp with time zone,
    expected_closing_date date,
    sales_id bigint,
    index smallint,
    organisation_id uuid not null default private.current_organisation_id()
);

create table public.deal_notes (
    id bigint generated by default as identity (sequence name public."dealNotes_id_seq") not null,
    deal_id bigint not null,
    type text,
    text text,
    date timestamp with time zone default now(),
    sales_id bigint,
    attachments jsonb[],
    organisation_id uuid not null default private.current_organisation_id()
);

create table public.sales (
    id bigint generated by default as identity primary key,
    first_name text not null default 'Pending'::text,
    last_name text not null default 'Pending'::text,
    email extensions.citext not null,
    administrator boolean not null,
    user_id uuid not null,
    avatar jsonb,
    disabled boolean not null default false,
    secondary_emails jsonb not null default '[]'::jsonb,
    organisation_id uuid not null default private.current_organisation_id(),
    constraint sales_secondary_emails_is_array check (jsonb_typeof(secondary_emails) = 'array')
);

create unique index uq__sales__user_id on public.sales using btree (user_id);

create table public.tags (
    id bigint generated by default as identity primary key,
    name text not null,
    color text not null,
    organisation_id uuid not null default private.current_organisation_id()
);

create table public.tasks (
    id bigint generated by default as identity primary key,
    contact_id bigint not null,
    type text,
    text text,
    due_date timestamp with time zone,
    done_date timestamp with time zone,
    sales_id bigint,
    created_at timestamp with time zone not null default now(),
    organisation_id uuid not null default private.current_organisation_id()
);

-- One configuration row per organisation. The frontend still reads and
-- writes `id = 1`; row-level security narrows that to the caller's own row.
create table public.configuration (
    id integer not null default 1,
    config jsonb not null default '{}'::jsonb,
    organisation_id uuid not null default private.current_organisation_id(),
    constraint configuration_pkey primary key (organisation_id),
    constraint configuration_singleton check (id = 1)
);

create table public.favicons_excluded_domains (
    id bigint generated by default as identity primary key,
    domain text not null
);

--
-- Tenant keys
-- (id, organisation_id) is unique on every table that other tenant rows point
-- at, so child rows can reference parents through composite foreign keys.
-- That makes the database itself refuse links across organisations.
--

alter table public.companies
    add constraint companies_id_organisation_id_key unique (id, organisation_id);

alter table public.contacts
    add constraint contacts_id_organisation_id_key unique (id, organisation_id);

alter table public.deals
    add constraint deals_id_organisation_id_key unique (id, organisation_id);

alter table public.sales
    add constraint sales_id_organisation_id_key unique (id, organisation_id);

