--
-- Tenancy
-- Organisations (tenants), memberships, and the helper functions every
-- row-level security policy uses. This file sorts first because table
-- defaults in 01_tables.sql call private.current_organisation_id().
--

create schema if not exists "private";

create type public.membership_role as enum ('org_admin', 'clinical_lead', 'key_worker', 'viewer');

create table public.organisations (
    id uuid primary key default gen_random_uuid(),
    name text not null,
    created_at timestamp with time zone not null default now(),
    constraint organisations_name_not_blank check (length(btrim(name)) > 0)
);

-- One organisation per user for now: unique (user_id) keeps "which
-- organisation am I acting in?" unambiguous without an organisation switcher.
create table public.memberships (
    id bigint generated by default as identity primary key,
    organisation_id uuid not null,
    user_id uuid not null,
    role public.membership_role not null default 'key_worker'::public.membership_role,
    created_at timestamp with time zone not null default now(),
    constraint memberships_one_organisation_per_user unique (user_id),
    constraint memberships_user_id_organisation_id_key unique (user_id, organisation_id)
);

alter table public.memberships
    add constraint memberships_organisation_id_fkey foreign key (organisation_id) references public.organisations(id);

alter table public.memberships
    add constraint memberships_user_id_fkey foreign key (user_id) references auth.users(id);

create index memberships_organisation_id_idx on public.memberships using btree (organisation_id);

-- The caller's organisation, or NULL when they have no membership.
-- SECURITY DEFINER so it can read memberships regardless of that table's RLS;
-- the empty search_path stops it being redirected to look-alike objects.
create or replace function private.current_organisation_id()
returns uuid
language sql
stable
security definer
set search_path to ''
as $$
  select m.organisation_id
  from public.memberships m
  where m.user_id = auth.uid()
$$;

-- The caller's role in their organisation, or NULL when they have no membership.
create or replace function private.current_membership_role()
returns public.membership_role
language sql
stable
security definer
set search_path to ''
as $$
  select m.role
  from public.memberships m
  where m.user_id = auth.uid()
$$;
