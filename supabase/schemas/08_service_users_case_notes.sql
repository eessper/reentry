--
-- Case notes and actions
-- What staff write down about a service user, and the follow-ups they agree.
-- Both are children of service_users (see 08_service_users.sql): same
-- tenancy pattern, and their policies check the parent with
-- `exists (select ... from service_users)`, so a key worker only reaches the
-- notes and actions of the people assigned to them and viewers reach none.
--
-- The author of a note and the creator of an action are stamped from the
-- signed-in member, never taken from the request.
--

create table public.case_notes (
    id bigint generated by default as identity primary key,
    organisation_id uuid not null default private.current_organisation_id(),
    service_user_id bigint not null,
    author_sales_id bigint,
    body text not null,
    created_at timestamp with time zone not null default now(),
    updated_at timestamp with time zone not null default now(),
    constraint case_notes_id_organisation_id_key unique (id, organisation_id),
    constraint case_notes_body_length check (length(btrim(body)) between 1 and 5000)
);

create table public.case_actions (
    id bigint generated by default as identity primary key,
    organisation_id uuid not null default private.current_organisation_id(),
    service_user_id bigint not null,
    title text not null,
    due_date date,
    assigned_to bigint,
    done_at timestamp with time zone,
    created_by bigint,
    created_at timestamp with time zone not null default now(),
    constraint case_actions_id_organisation_id_key unique (id, organisation_id),
    constraint case_actions_title_length check (length(btrim(title)) between 1 and 200)
);

alter table public.case_notes
    add constraint case_notes_organisation_id_fkey foreign key (organisation_id) references public.organisations(id);
alter table public.case_notes
    add constraint case_notes_service_user_id_fkey foreign key (service_user_id, organisation_id) references public.service_users(id, organisation_id) on delete cascade;
alter table public.case_notes
    add constraint case_notes_author_sales_id_fkey foreign key (author_sales_id, organisation_id) references public.sales(id, organisation_id);

alter table public.case_actions
    add constraint case_actions_organisation_id_fkey foreign key (organisation_id) references public.organisations(id);
alter table public.case_actions
    add constraint case_actions_service_user_id_fkey foreign key (service_user_id, organisation_id) references public.service_users(id, organisation_id) on delete cascade;
alter table public.case_actions
    add constraint case_actions_assigned_to_fkey foreign key (assigned_to, organisation_id) references public.sales(id, organisation_id);
alter table public.case_actions
    add constraint case_actions_created_by_fkey foreign key (created_by, organisation_id) references public.sales(id, organisation_id);

create index case_notes_service_user_id_created_at_idx on public.case_notes using btree (service_user_id, created_at desc);
create index case_notes_organisation_id_idx on public.case_notes using btree (organisation_id);
create index case_actions_service_user_id_idx on public.case_actions using btree (service_user_id);
create index case_actions_organisation_id_idx on public.case_actions using btree (organisation_id);

--
-- Triggers
--

-- A note is always in the name of the member who wrote it, and stays
-- attached to the same person and author when edited.
create or replace function public.stamp_case_note()
returns trigger
language plpgsql
set search_path to ''
as $$
begin
  if tg_op = 'INSERT' then
    if auth.uid() is not null then
      new.author_sales_id := private.current_sales_id();
    end if;
  else
    new.service_user_id := old.service_user_id;
    new.author_sales_id := old.author_sales_id;
    new.created_at := old.created_at;
    new.updated_at := now();
  end if;
  return new;
end;
$$;

-- An action is created in the name of the signed-in member and stays
-- attached to the same person.
create or replace function public.stamp_case_action()
returns trigger
language plpgsql
set search_path to ''
as $$
begin
  if tg_op = 'INSERT' then
    if auth.uid() is not null then
      new.created_by := private.current_sales_id();
    end if;
  else
    new.service_user_id := old.service_user_id;
    new.created_by := old.created_by;
    new.created_at := old.created_at;
  end if;
  return new;
end;
$$;

create or replace trigger stamp_case_note
    before insert or update on public.case_notes
    for each row execute function public.stamp_case_note();

create or replace trigger stamp_case_action
    before insert or update on public.case_actions
    for each row execute function public.stamp_case_action();

--
-- Row-level security
--

alter table public.case_notes enable row level security;
alter table public.case_actions enable row level security;

-- Case notes: follow their service user. Only the author edits a note; only
-- leads delete one.
create policy "Notes of visible service users" on public.case_notes for select to authenticated
    using (
        organisation_id = (select private.current_organisation_id())
        and exists (select 1 from public.service_users su where su.id = service_user_id)
    );
create policy "Write notes for visible service users" on public.case_notes for insert to authenticated
    with check (
        organisation_id = (select private.current_organisation_id())
        and exists (select 1 from public.service_users su where su.id = service_user_id)
    );
create policy "Authors edit their notes" on public.case_notes for update to authenticated
    using (
        organisation_id = (select private.current_organisation_id())
        and author_sales_id = (select private.current_sales_id())
        and exists (select 1 from public.service_users su where su.id = service_user_id)
    )
    with check (
        organisation_id = (select private.current_organisation_id())
        and author_sales_id = (select private.current_sales_id())
        and exists (select 1 from public.service_users su where su.id = service_user_id)
    );
create policy "Leads delete notes" on public.case_notes for delete to authenticated
    using (
        organisation_id = (select private.current_organisation_id())
        and (select private.sees_all_records())
        and exists (select 1 from public.service_users su where su.id = service_user_id)
    );

-- Case actions: follow their service user. Leads, or whoever created the
-- action, can delete it.
create policy "Actions of visible service users" on public.case_actions for select to authenticated
    using (
        organisation_id = (select private.current_organisation_id())
        and exists (select 1 from public.service_users su where su.id = service_user_id)
    );
create policy "Add actions for visible service users" on public.case_actions for insert to authenticated
    with check (
        organisation_id = (select private.current_organisation_id())
        and exists (select 1 from public.service_users su where su.id = service_user_id)
    );
create policy "Update actions of visible service users" on public.case_actions for update to authenticated
    using (
        organisation_id = (select private.current_organisation_id())
        and exists (select 1 from public.service_users su where su.id = service_user_id)
    )
    with check (
        organisation_id = (select private.current_organisation_id())
        and exists (select 1 from public.service_users su where su.id = service_user_id)
    );
create policy "Leads or creators delete actions" on public.case_actions for delete to authenticated
    using (
        organisation_id = (select private.current_organisation_id())
        and ((select private.sees_all_records()) or created_by = (select private.current_sales_id()))
        and exists (select 1 from public.service_users su where su.id = service_user_id)
    );

--
-- Grants (anon gets nothing)
--

revoke all on table public.case_notes from anon;
revoke all on table public.case_notes from authenticated;
grant select, insert, update, delete on table public.case_notes to authenticated;
grant all on table public.case_notes to service_role;

revoke all on table public.case_actions from anon;
revoke all on table public.case_actions from authenticated;
grant select, insert, update, delete on table public.case_actions to authenticated;
grant all on table public.case_actions to service_role;

revoke all on sequence public.case_notes_id_seq from anon;
revoke all on sequence public.case_actions_id_seq from anon;

revoke all on function public.stamp_case_note() from public;
revoke all on function public.stamp_case_note() from anon;
revoke all on function public.stamp_case_action() from public;
revoke all on function public.stamp_case_action() from anon;
