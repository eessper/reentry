-- Service users: key workers read and update only the people assigned to
-- them and can't hand them to someone else; creating, removing and
-- (re)assigning service users is for org admins and clinical leads.
create policy "Read assigned service users, or all for leads" on public.service_users for select to authenticated
    using (
        organisation_id = (select private.current_organisation_id())
        and (
            (select private.sees_all_records())
            or ((select private.current_membership_role()) = 'key_worker' and assigned_worker_id = (select private.current_sales_id()))
        )
    );
create policy "Update assigned service users, or all for leads" on public.service_users for update to authenticated
    using (
        organisation_id = (select private.current_organisation_id())
        and (
            (select private.sees_all_records())
            or ((select private.current_membership_role()) = 'key_worker' and assigned_worker_id = (select private.current_sales_id()))
        )
    )
    with check (
        organisation_id = (select private.current_organisation_id())
        and (
            (select private.sees_all_records())
            or ((select private.current_membership_role()) = 'key_worker' and assigned_worker_id = (select private.current_sales_id()))
        )
    );
create policy "Leads create service users" on public.service_users for insert to authenticated
    with check (organisation_id = (select private.current_organisation_id()) and (select private.sees_all_records()));
create policy "Leads delete service users" on public.service_users for delete to authenticated
    using (organisation_id = (select private.current_organisation_id()) and (select private.sees_all_records()));

-- Support profiles: follow their service user. Created by the trigger above,
-- removed with their service user.
create policy "Profiles of visible service users" on public.support_profiles for select to authenticated
    using (
        organisation_id = (select private.current_organisation_id())
        and exists (select 1 from public.service_users su where su.id = service_user_id)
    );
create policy "Update profiles of visible service users" on public.support_profiles for update to authenticated
    using (
        organisation_id = (select private.current_organisation_id())
        and exists (select 1 from public.service_users su where su.id = service_user_id)
    )
    with check (
        organisation_id = (select private.current_organisation_id())
        and exists (select 1 from public.service_users su where su.id = service_user_id)
    );

-- Escalations: follow their service user. Only leads delete them.
create policy "Escalations of visible service users" on public.escalations for select to authenticated
    using (
        organisation_id = (select private.current_organisation_id())
        and exists (select 1 from public.service_users su where su.id = service_user_id)
    );
create policy "Open escalations for visible service users" on public.escalations for insert to authenticated
    with check (
        organisation_id = (select private.current_organisation_id())
        and exists (select 1 from public.service_users su where su.id = service_user_id)
    );
create policy "Handle escalations of visible service users" on public.escalations for update to authenticated
    using (
        organisation_id = (select private.current_organisation_id())
        and exists (select 1 from public.service_users su where su.id = service_user_id)
    )
    with check (
        organisation_id = (select private.current_organisation_id())
        and exists (select 1 from public.service_users su where su.id = service_user_id)
    );
create policy "Leads delete escalations" on public.escalations for delete to authenticated
    using (
        organisation_id = (select private.current_organisation_id())
        and (select private.sees_all_records())
        and exists (select 1 from public.service_users su where su.id = service_user_id)
    );

-- Activity events: follow their service user; added, never changed (no
-- update or delete grant).
create policy "Events of visible service users" on public.activity_events for select to authenticated
    using (
        organisation_id = (select private.current_organisation_id())
        and exists (select 1 from public.service_users su where su.id = service_user_id)
    );
create policy "Record events for visible service users" on public.activity_events for insert to authenticated
    with check (
        organisation_id = (select private.current_organisation_id())
        and exists (select 1 from public.service_users su where su.id = service_user_id)
    );

