--
-- Service users
-- The people Re-entry supports, their support profile (the "Clinical Profile
-- Configuration" screen), escalations needing a human, and the activity feed.
--
-- Same tenancy pattern as every tenant table (see 00_tenancy.sql): an
-- organisation_id defaulting to the caller's organisation, a unique
-- (id, organisation_id) key, and composite foreign keys so no row can point
-- at another organisation's row. Role rules follow 05_policies.sql:
-- service_users is assignable (like contacts, through assigned_worker_id);
-- the other tables are children that follow their service user.
--
-- None of these tables has a trigger calling outside services (unlike
-- contacts and companies, see finding F7).
--

create type public.risk_tier as enum ('low', 'moderate', 'moderate_high', 'high');
create type public.service_user_status as enum ('active', 'paused', 'exited');
create type public.consent_status as enum ('pending', 'given', 'withdrawn');
create type public.risk_pathway as enum ('substance_use', 'housing_instability', 'financial_stress', 'interpersonal_conflict');
create type public.cbt_module as enum ('distress_tolerance', 'cognitive_reframing', 'emotional_regulation', 'urge_surfing', 'radical_acceptance');
create type public.checkin_frequency as enum ('twice_daily', 'daily', 'every_other_day', 'weekly');
create type public.escalation_trigger as enum ('keyword', 'sentiment_dip', 'missed_checkins', 'manual', 'self_referral');
create type public.escalation_severity as enum ('low', 'medium', 'high', 'critical');
create type public.escalation_status as enum ('open', 'acknowledged', 'resolved');
create type public.activity_event_type as enum ('checkin', 'missed_checkin', 'cbt_deploy', 'logistics', 'escalation', 'override', 'profile_change');

--
-- Tables
--

create table public.service_users (
    id bigint generated by default as identity primary key,
    organisation_id uuid not null default private.current_organisation_id(),
    display_name text not null,
    reference_code text not null,
    release_date date not null,
    risk_tier public.risk_tier not null default 'moderate'::public.risk_tier,
    assigned_worker_id bigint,
    consent_status public.consent_status not null default 'pending'::public.consent_status,
    status public.service_user_status not null default 'active'::public.service_user_status,
    created_at timestamp with time zone not null default now(),
    updated_at timestamp with time zone not null default now(),
    constraint service_users_id_organisation_id_key unique (id, organisation_id),
    constraint service_users_reference_code_key unique (organisation_id, reference_code),
    constraint service_users_reference_code_format check (reference_code ~ '^RE-[0-9]{5}$'),
    constraint service_users_display_name_not_blank check (length(btrim(display_name)) > 0)
);

-- One profile per service user, created with defaults when the service user
-- is created. `version` goes up by one on every change.
create table public.support_profiles (
    id bigint generated by default as identity primary key,
    organisation_id uuid not null default private.current_organisation_id(),
    service_user_id bigint not null,
    primary_risk_pathway public.risk_pathway,
    active_cbt_module public.cbt_module,
    checkin_frequency public.checkin_frequency not null default 'daily'::public.checkin_frequency,
    sentiment_dip_days smallint not null default 3,
    missed_checkins_threshold smallint not null default 2,
    keyword_sensitivity smallint not null default 5,
    version integer not null default 1,
    updated_at timestamp with time zone not null default now(),
    updated_by bigint,
    constraint support_profiles_id_organisation_id_key unique (id, organisation_id),
    constraint support_profiles_service_user_id_key unique (service_user_id),
    constraint support_profiles_sentiment_dip_days_range check (sentiment_dip_days between 1 and 14),
    constraint support_profiles_missed_checkins_threshold_range check (missed_checkins_threshold between 1 and 10),
    constraint support_profiles_keyword_sensitivity_range check (keyword_sensitivity between 1 and 10)
);

create table public.escalations (
    id bigint generated by default as identity primary key,
    organisation_id uuid not null default private.current_organisation_id(),
    service_user_id bigint not null,
    trigger_type public.escalation_trigger not null,
    severity public.escalation_severity not null,
    status public.escalation_status not null default 'open'::public.escalation_status,
    assigned_to bigint,
    opened_at timestamp with time zone not null default now(),
    acknowledged_at timestamp with time zone,
    resolved_at timestamp with time zone,
    notes text,
    constraint escalations_id_organisation_id_key unique (id, organisation_id),
    constraint escalations_acknowledged_when_handled check (status = 'open'::public.escalation_status or acknowledged_at is not null),
    constraint escalations_resolved_when_resolved check ((status = 'resolved'::public.escalation_status) = (resolved_at is not null))
);

-- The "Live Action Logs" feed. Written by people and (in Phase 2) the
-- WhatsApp engine; never edited afterwards.
create table public.activity_events (
    id bigint generated by default as identity primary key,
    organisation_id uuid not null default private.current_organisation_id(),
    service_user_id bigint not null,
    type public.activity_event_type not null,
    summary text not null,
    actor_sales_id bigint,
    created_at timestamp with time zone not null default now(),
    constraint activity_events_id_organisation_id_key unique (id, organisation_id)
);

