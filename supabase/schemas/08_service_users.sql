--
-- Functions and triggers
--

-- Every service user starts with a default support profile, so the profile
-- screen always has one to show. SECURITY DEFINER because whoever may create
-- the service user may also get its profile, whatever the profile policies.
create or replace function public.handle_service_user_created()
returns trigger
language plpgsql
security definer
set search_path to ''
as $$
begin
  insert into public.support_profiles (organisation_id, service_user_id)
  values (new.organisation_id, new.id);
  return new;
end;
$$;

create or replace function public.touch_service_user()
returns trigger
language plpgsql
set search_path to ''
as $$
begin
  new.updated_at := now();
  return new;
end;
$$;

-- Each saved change to a profile is a new version, stamped with who made it.
create or replace function public.version_support_profile()
returns trigger
language plpgsql
set search_path to ''
as $$
begin
  new.version := old.version + 1;
  new.updated_at := now();
  new.updated_by := coalesce(private.current_sales_id(), new.updated_by);
  return new;
end;
$$;

-- Acknowledging or resolving an escalation stamps the time it happened.
create or replace function public.stamp_escalation_status()
returns trigger
language plpgsql
set search_path to ''
as $$
begin
  if new.status <> 'open' and new.acknowledged_at is null then
    new.acknowledged_at := now();
  end if;
  if new.status = 'resolved' and new.resolved_at is null then
    new.resolved_at := now();
  end if;
  if new.status <> 'resolved' then
    new.resolved_at := null;
  end if;
  return new;
end;
$$;

create or replace trigger on_service_user_created
    after insert on public.service_users
    for each row execute function public.handle_service_user_created();

create or replace trigger touch_service_user
    before update on public.service_users
    for each row execute function public.touch_service_user();

create or replace trigger version_support_profile
    before update on public.support_profiles
    for each row execute function public.version_support_profile();

create or replace trigger stamp_escalation_status
    before insert or update of status on public.escalations
    for each row execute function public.stamp_escalation_status();

